// --- Pages ---------------------------------------------------------------------

const PLACEHOLDER_LINE = 'Fill in a placeholder once and every command uses it.';
const pages = new Map(); // file path -> html
const urls = [];

function add(path, opts) {
  pages.set(join(path, 'index.html'), page({ path, ...opts }));
  urls.push(SITE + path);
}

add('', {
  root: '',
  title: 'Cloud runbook · Yash Verma',
  description: 'Generic, copy-ready commands and short incident playbooks for Kubernetes, AWS, GCP, Terraform, Docker, Linux and the tools around them. Risky commands are marked.',
  h1: 'Cloud runbook',
  standfirst: `Commands I reach for across Kubernetes, AWS, GCP, Terraform, Linux and the tools around them, plus short <a href="playbooks/">playbooks</a> for common incidents. ${PLACEHOLDER_LINE}`,
  current: 'all',
  count: `${commands.length} commands in ${categories.length} categories`,
  view: categories.map((cat) => groupHtml(cat, inCat(cat))).join(''),
});

for (const cat of categories) {
  const list = inCat(cat);
  const cautions = list.filter((c) => c.warn).length;
  add(`${slug(cat)}/`, {
    root: '../',
    title: `${cat} commands · Cloud runbook · Yash Verma`,
    description: `${list.length} copy-ready ${cat} commands, each with what it does${cautions ? ' and a caution on the risky ones' : ''}: ${list
      .slice(0, 3)
      .map((c) => c.title.toLowerCase())
      .join(', ')} and more.`,
    h1: `${cat} commands`,
    standfirst: `${plural(list.length, 'command', 'commands')} from the <a href="../">cloud runbook</a>. ${PLACEHOLDER_LINE}`,
    current: cat,
    count: `${plural(list.length, 'command', 'commands')} in ${cat}`,
    view: list.map((c) => commandHtml(c, { root: '../' })).join(''),
  });
}

add('playbooks/', {
  root: '../',
  title: 'Playbooks · Cloud runbook · Yash Verma',
  description: `Step-by-step procedures for common incidents: ${playbooks.map((p) => p.title.toLowerCase()).join(', ')}.`,
  h1: 'Playbooks',
  standfirst: 'Short procedures for common incidents. Each step carries the command it needs.',
  current: 'playbooks',
  count: plural(playbooks.length, 'playbook', 'playbooks'),
  view: playbookListHtml(playbooks, { root: '../' }),
});

for (const p of playbooks) {
  add(`playbooks/${p.id}/`, {
    root: '../../',
    title: `${p.title} · Playbooks · Cloud runbook`,
    description: `${p.summary} ${plural(p.steps.length, 'step', 'steps')}, each with the command it needs.`,
    h1: p.title,
    standfirst: `${esc(p.summary)} <a href="../">All playbooks</a>.`,
    current: 'playbooks',
    count: plural(p.steps.length, 'step', 'steps'),
    view: playbookHtml(p, byId, { root: '../../' }),
  });
}

// 404.html is served for any missing path, at any depth, so it uses absolute URLs.
pages.set(
  '404.html',
  page({
    path: '404.html',
    root: '/yv-cloud-runbook/',
    title: 'Page not found · Cloud runbook',
    description: 'This page does not exist.',
    h1: 'Page not found',
    standfirst: 'There is no page at this address. The <a href="/yv-cloud-runbook/">runbook</a> lists every command, or search below.',
    current: 'none',
    count: `${commands.length} commands`,
    view: '',
    robots: '<meta name="robots" content="noindex" />',
  }),
);

pages.set(
  'sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u}</loc></url>`).join('\n')}
</urlset>
`,
);

// --- Write or check --------------------------------------------------------------

// Pages from an earlier build whose category or playbook no longer exists.
const previous = existsSync(join(ROOT, 'sitemap.xml'))
  ? [...readFileSync(join(ROOT, 'sitemap.xml'), 'utf8').matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].slice(SITE.length))
  : [];
const orphans = previous
  .map((p) => join(p, 'index.html'))
  .filter((f) => dirname(f) !== '.' && !pages.has(f) && existsSync(join(ROOT, f)) && readFileSync(join(ROOT, f), 'utf8').includes(MARK));

if (process.argv.includes('--check')) {
  const stale = [...pages].filter(([f, html]) => !existsSync(join(ROOT, f)) || readFileSync(join(ROOT, f), 'utf8') !== html).map(([f]) => f);
  if (stale.length || orphans.length) {
    console.error(`Out of date; run node tools/build.mjs and commit:\n  ${[...stale, ...orphans.map((f) => `${f} (remove)`)].join('\n  ')}`);
    process.exit(1);
  }
  console.log(`Up to date: ${pages.size} files.`);
} else {
  for (const [f, html] of pages) {
    mkdirSync(dirname(join(ROOT, f)), { recursive: true });
    writeFileSync(join(ROOT, f), html);
  }
  for (const f of orphans) rmSync(dirname(join(ROOT, f)), { recursive: true });
  console.log(`Wrote ${pages.size} files${orphans.length ? `, removed ${orphans.length} old pages` : ''}.`);
}
