// Cloud runbook: pre-renders every page from commands.js and playbooks.js.
//
//   node tools/build.mjs           write the pages
//   node tools/build.mjs --check   fail if any page is out of date (run in CI)
//
// Node built-ins only. The output is committed: GitHub Pages serves it as it is.

import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { commands } from '../commands.js';
import { playbooks } from '../playbooks.js';
import { esc, slug, plural, categoryUrl, playbookUrl, commandHtml, groupHtml, playbookListHtml, playbookHtml } from '../render.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://yashverma-cloud.github.io/yv-cloud-runbook/';
const MARK = '<!-- Generated by tools/build.mjs from commands.js and playbooks.js. Edit those, then run: node tools/build.mjs -->';
const RESERVED = new Set(['playbooks', 'fonts', 'tools', 'github']);

// --- Validate the data ------------------------------------------------------

const problems = [];
const ids = new Set();
for (const c of commands) {
  for (const k of ['id', 'category', 'title', 'description', 'command']) {
    if (typeof c[k] !== 'string' || !c[k].trim()) problems.push(`${c.id || '?'}: missing ${k}`);
  }
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(c.id)) problems.push(`${c.id}: id must be lower-case words joined by hyphens`);
  if (ids.has(c.id)) problems.push(`${c.id}: duplicate id`);
  ids.add(c.id);
  if (!Array.isArray(c.tags) || c.tags.some((t) => typeof t !== 'string')) problems.push(`${c.id}: tags must be strings`);
  for (const k of ['warn', 'note']) if (k in c && typeof c[k] !== 'string') problems.push(`${c.id}: ${k} must be a string`);
}
const categories = [...new Set(commands.map((c) => c.category))];
const slugs = new Set();
for (const cat of categories) {
  const s = slug(cat);
  if (slugs.has(s) || RESERVED.has(s)) problems.push(`category "${cat}": slug "${s}" is taken`);
  slugs.add(s);
}
const byId = new Map(commands.map((c) => [c.id, c]));
const pbIds = new Set();
for (const p of playbooks) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(p.id) || pbIds.has(p.id)) problems.push(`playbook ${p.id}: bad or duplicate id`);
  pbIds.add(p.id);
  p.steps.forEach((s, i) => {
    if (!s.text) problems.push(`playbook ${p.id} step ${i + 1}: missing text`);
    if (s.cmd && !byId.has(s.cmd)) problems.push(`playbook ${p.id} step ${i + 1}: unknown command "${s.cmd}"`);
    if (s.cmd && s.run) problems.push(`playbook ${p.id} step ${i + 1}: use cmd or run, not both`);
  });
}
if (problems.length) {
  console.error(`Data problems:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const inCat = (cat) => commands.filter((c) => c.category === cat);

// --- Page shell ----------------------------------------------------------------

function nav(root, current) {
  const item = (href, label, n, key, extra = '') =>
    `<li${extra}><a href="${href}"${key === current ? ' aria-current="page"' : ''}><span>${esc(label)}</span><span class="n">${n}</span></a></li>`;
  const opt = (href, label, key) => `<option value="${href}"${key === current ? ' selected' : ''}>${esc(label)}</option>`;
  const home = root || './';
  return `
      <nav class="cats" aria-label="Categories">
        <label class="micro cat-select-label" for="cat-select">Category</label>
        <select id="cat-select">
          ${opt(home, `All commands (${commands.length})`, 'all')}
          ${categories.map((c) => opt(categoryUrl(root, c), `${c} (${inCat(c).length})`, c)).join('\n          ')}
          ${opt(`${root}playbooks/`, `Playbooks (${playbooks.length})`, 'playbooks')}
        </select>
        <ul class="cat-list">
          ${item(home, 'All commands', commands.length, 'all')}
          ${categories.map((c) => item(categoryUrl(root, c), c, inCat(c).length, c)).join('\n          ')}
          ${item(`${root}playbooks/`, 'Playbooks', playbooks.length, 'playbooks', ' class="group-start"')}
        </ul>
      </nav>`;
}

